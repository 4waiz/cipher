"""Corpus statistics for the paper and site, computed from the frozen manifest and logs.

Writes paper/generated/corpus.tex (LaTeX macros) and analysis/exports/corpus.json.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> None:
    import sys
    sys.path.insert(0, str(ROOT / "src"))
    from cipher.acquire import build_frame
    from cipher.practice import practice_items

    cases = json.loads((ROOT / "data" / "cases" / "manifest.json").read_text(encoding="utf-8"))
    sel = json.loads((ROOT / "data" / "cases" / "selection_log.json").read_text(encoding="utf-8"))
    acq = json.loads((ROOT / "data" / "acquisition_log.json").read_text(encoding="utf-8"))
    frame = build_frame()
    ev = [c for c in cases if c["split"] == "evaluation"]
    orig = [c for c in ev if c["stratum"] == "original"]
    var = [c for c in ev if c["stratum"] == "context_variant"]
    ctl = [c for c in ev if c["stratum"] == "order_control"]
    cal = [c for c in cases if c["split"] == "calibration"]
    rel = Counter(c["relation"] for c in orig)
    chg = Counter(c["changed_property"] for c in var)
    eval_repos = sorted({c["repo"] for c in ev})
    cal_repos = sorted({c["repo"] for c in cal})
    tried = acq["tried"]
    snap_ok = [t for t in tried if t["status"] == "eligible"]
    pair_ok = [r for r in sel["repos"] if r["decision"] in ("calibration", "evaluation", "reserve (not used)")]
    agents_files = {}
    for r in eval_repos + cal_repos:
        s = json.loads((ROOT / "data" / "snapshots" / (r.replace("/", "__") + ".json")).read_text(encoding="utf-8"))
        agents_files[r] = {"files": len(s["agents_files"]), "license": s["license"], "commit": s["commit"]}
    stats = {
        "frame_size": len(frame), "retrieved": len(tried), "snapshot_eligible": len(snap_ok),
        "pair_eligible": len(pair_ok), "calibration_repos": cal_repos, "evaluation_repos": eval_repos,
        "calibration_originals": sum(1 for c in cal if c["stratum"] == "original"),
        "calibration_variants": sum(1 for c in cal if c["stratum"] == "context_variant"),
        "originals": len(orig), "variants": len(var), "controls": len(ctl),
        "relation_counts": dict(rel), "variant_changes": dict(chg),
        "originals_per_repo": dict(Counter(c["repo"] for c in orig)),
        "agents_files": agents_files,
        "task_templates": dict(Counter(c["task"].split("`")[0].strip() for c in orig)),
    }
    out = ROOT / "analysis" / "exports"
    out.mkdir(parents=True, exist_ok=True)
    (out / "corpus.json").write_text(json.dumps(stats, indent=1), encoding="utf-8", newline="\n")
    words = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine"}
    lines = [
        "% Generated by analysis/corpus_stats.py from data/cases/manifest.json. Do not edit.",
        macro("NFrame", stats["frame_size"]), macro("NRetrieved", stats["retrieved"]),
        macro("NSnapshotEligible", stats["snapshot_eligible"]), macro("NPairEligible", stats["pair_eligible"]),
        macro("NEvalRepos", len(eval_repos)), macro("NEvalReposWord", words.get(len(eval_repos), len(eval_repos))),
        macro("NCalRepos", len(cal_repos)), macro("NCalReposWord", words.get(len(cal_repos), len(cal_repos))),
        macro("NCalOriginals", stats["calibration_originals"]), macro("NCalVariants", stats["calibration_variants"]),
        macro("NOriginals", len(orig)), macro("NVariants", len(var)), macro("NControls", len(ctl)),
        macro("NEvalContexts", len(ev)), macro("NAnnotated", len(orig) + len(var)),
        macro("NRelAncestor", rel.get("ancestor_descendant", 0)), macro("NRelUnrelated", rel.get("unrelated", 0)),
        macro("NRelSameFile", rel.get("same_file", 0)),
        macro("NVarTarget", chg.get("target_path", 0)), macro("NVarPlacement", chg.get("source_placement", 0)),
        macro("NEvalAgentsFiles", sum(agents_files[r]["files"] for r in eval_repos)),
        macro("NPractice", len(practice_items())), macro("NPracticeWord", words.get(len(practice_items()))),
        macro("NCalItems", len(practice_items()) + len(cal)),
    ]
    gen = ROOT / "paper" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "corpus.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({k: v for k, v in stats.items() if k not in ("agents_files",)}, indent=1))


if __name__ == "__main__":
    main()
