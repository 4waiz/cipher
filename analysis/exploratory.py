"""Exploratory (post-hoc) checks added after unsealing, prompted by the final manuscript review (plan addendum A3).

1. Repeat variability: B1R's first call sends exactly the request B1 sent (same prompt, evidence and seed), but on a
   later Ollama patch version. Label differences between the two estimate run-to-run variation, against which the
   order-control and between-method differences must be read.
2. How often B1's explanations on profile-determined cases cite the off-chain instruction file.

Writes analysis/exports/exploratory.json and paper/generated/exploratory.tex. Nothing in the frozen analysis changes.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from cipher.profile import loaded_set  # noqa: E402


def main() -> None:
    cases = {c["case_id"]: c for c in json.loads((ROOT / "data/cases/manifest.json").read_text(encoding="utf-8"))
             if c["split"] == "evaluation"}
    runs = json.loads((ROOT / "configs/heldout_runs.json").read_text(encoding="utf-8"))
    P = {m: {json.loads(x)["case_id"]: json.loads(x) for x in
             (ROOT / "runs/heldout" / runs[m] / "predictions.jsonl").read_text(encoding="utf-8").splitlines() if x}
         for m in ("B1", "B1R")}
    same_request = sum(1 for c in cases if P["B1"][c]["attempts"][0]["request_sha256"] ==
                       P["B1R"][c]["attempts"][0]["request_sha256"])
    differs = Counter(cases[c]["stratum"] for c in cases if P["B1"][c]["label"] != P["B1R"][c]["first_label"])
    n = Counter(cases[c]["stratum"] for c in cases)
    pd_cite, pd_n = 0, 0
    for c, x in cases.items():
        pk = x["packet"]
        chain = loaded_set(x["target_path"], pk["agents_paths"])
        off = [pk[r]["path"] for r in ("rule_1", "rule_2") if pk[r]["path"] not in chain]
        if off and x["stratum"] != "order_control":
            pd_n += 1
            text = (P["B1"][c].get("explanation") or "") + " " + " ".join(P["B1"][c].get("evidence") or [])
            pd_cite += any(p in text for p in off)
    res = {"note": "exploratory, post-hoc (analysis plan addendum A3)",
           "repeat": {"identical_requests": same_request, "n": len(cases),
                      "label_differs": dict(differs), "label_differs_total": sum(differs.values()),
                      "strata_n": dict(n), "runtime": "B1 on Ollama 0.40.6, B1R first call on 0.40.7"},
           "b1_pd_cites_offchain_file": {"k": pd_cite, "n": pd_n}}
    (ROOT / "analysis/exports/exploratory.json").write_text(json.dumps(res, indent=1), encoding="utf-8", newline="\n")
    L = ["% Generated by analysis/exploratory.py (exploratory, post-hoc). Do not edit.",
         f"\\newcommand{{\\RepeatIdentical}}{{{same_request}}}",
         f"\\newcommand{{\\RepeatDiffTotal}}{{{sum(differs.values())}}}",
         f"\\newcommand{{\\RepeatDiffOrig}}{{{differs.get('original', 0)}}}",
         f"\\newcommand{{\\RepeatDiffVar}}{{{differs.get('context_variant', 0)}}}",
         f"\\newcommand{{\\RepeatDiffCtrl}}{{{differs.get('order_control', 0)}}}",
         f"\\newcommand{{\\BOnePDCitesOffChain}}{{{pd_cite}}}"]
    (ROOT / "paper/generated/exploratory.tex").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(res, indent=1))


if __name__ == "__main__":
    main()
