#!/usr/bin/env python3
"""Build the CIPHER static website (Python standard library only).

Usage (from the repository root):
    python site/build.py
    python site/build.py --exports-dir PATH --paper-build-dir PATH --out PATH

What it does (see docs/site_contract.md):
  1. copies site/src/ to site/dist/;
  2. copies analysis/exports/*.json to dist/data/ and also inlines each one into
     dist/data/<name>.js (sets window.CIPHER_DATA[<name>]) so pages work from file://;
     a missing status/results/replay export is replaced by a stub with "available": false;
  3. copies paper/build/cipher-paper.pdf to dist/paper/cipher-paper.pdf when present;
  4. copies paper/build/figures/*.svg next to the paper page;
  5. renders dist/paper/index.html from site/templates/paper.html wrapping
     paper/build/paper.html + paper/build/meta.json, or a plain "manuscript not yet built" page;
  6. writes dist/data/build.json (+ .js), dist/.nojekyll.

The site never computes research numbers: it only copies and formats generated files.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import html
import json
import os
import re
import shutil
import subprocess
import stat
import sys
from html.parser import HTMLParser
from pathlib import Path

SITE = Path(__file__).resolve().parent
REPO = SITE.parent
SRC = SITE / "src"
TEMPLATES = SITE / "templates"
DEFAULT_OUT = SITE / "dist"
DEFAULT_EXPORTS = REPO / "analysis" / "exports"
DEFAULT_PAPER = REPO / "paper" / "build"

GITHUB_URL = "https://github.com/4waiz/cipher"
PDF_NAME = "cipher-paper.pdf"
REQUIRED_EXPORTS = ("status", "results", "replay")
LABELS = (
    "Unresolved conflict",
    "Valid override",
    "Disjoint applicability",
    "Compatible",
    "Insufficient evidence",
)
STRATA = ("original", "context_variant", "order_control")

warnings: list[str] = []


def warn(msg: str) -> None:
    warnings.append(msg)
    print(f"  warning: {msg}")


# ----------------------------------------------------------------------------- helpers


def display_path(p: Path) -> str:
    """Repository-relative path for messages and published metadata; never leak absolute local paths."""
    try:
        return p.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return f"<external {p.name}>"


def _on_rm_error(func, path, _exc):
    # OneDrive / Windows can leave files read-only; make writable and retry once.
    os.chmod(path, stat.S_IWRITE)
    func(path)


def clean_out(out: Path) -> None:
    out = out.resolve()
    forbidden = {REPO.resolve(), SITE.resolve(), SRC.resolve(), TEMPLATES.resolve(), Path(out.anchor)}
    if out in forbidden:
        sys.exit(f"error: refusing to use {out} as the output directory")
    if not out.exists():
        return
    is_default = out == DEFAULT_OUT.resolve()
    produced_by_us = (out / "data" / "build.json").is_file()
    if not (is_default or produced_by_us or not any(out.iterdir())):
        sys.exit(f"error: {out} exists and was not produced by this script; choose another --out")
    if sys.version_info >= (3, 12):
        shutil.rmtree(out, onexc=_on_rm_error)
    else:  # pragma: no cover
        shutil.rmtree(out, onerror=_on_rm_error)


def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        sys.exit(f"error: {display_path(path)} is not valid JSON: {exc}")


def js_assign(key: str, data) -> str:
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    # Safe inside a classic script: escape line separators and any closing-tag sequence.
    payload = payload.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029").replace("</", "<\\/")
    return (
        "/* Generated by site/build.py. Do not edit. */\n"
        "window.CIPHER_DATA = window.CIPHER_DATA || {};\n"
        f"window.CIPHER_DATA[{json.dumps(key)}] = {payload};\n"
    )


def write_data(out_data: Path, key: str, data, raw_source: Path | None = None) -> None:
    out_data.mkdir(parents=True, exist_ok=True)
    if raw_source is not None:
        shutil.copyfile(raw_source, out_data / f"{key}.json")
    else:
        (out_data / f"{key}.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (out_data / f"{key}.js").write_text(js_assign(key, data), encoding="utf-8")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def esc(value) -> str:
    return html.escape("" if value is None else str(value), quote=True)


# ----------------------------------------------------------------------------- contract checks (warn only)


def check_status(d) -> None:
    if not isinstance(d, dict):
        warn("status.json is not an object")
        return
    for key in ("version", "date", "status_label", "git_commit", "results_available"):
        if key not in d:
            warn(f"status.json: missing '{key}'")


def check_results(d) -> dict:
    info = {"available": None, "tables": 0, "figures": 0}
    if not isinstance(d, dict):
        warn("results.json is not an object")
        return info
    if not isinstance(d.get("available"), bool):
        warn("results.json: 'available' should be true or false")
    info["available"] = d.get("available") is True
    tables = d.get("tables") if isinstance(d.get("tables"), list) else []
    figures = d.get("figures") if isinstance(d.get("figures"), list) else []
    if info["available"]:
        if not isinstance(d.get("tables"), list):
            warn("results.json: 'tables' should be a list")
        for i, t in enumerate(tables):
            if not isinstance(t, dict) or not isinstance(t.get("columns"), list) or not isinstance(t.get("rows"), list):
                warn(f"results.json: table {i} lacks columns/rows lists")
                continue
            width = len(t["columns"])
            for j, row in enumerate(t["rows"]):
                if not isinstance(row, list) or len(row) != width:
                    warn(f"results.json: table '{t.get('id', i)}' row {j} does not have {width} cells")
                    break
        for f in figures:
            if not isinstance(f, dict) or not re.fullmatch(r"figures/[\w.-]+\.(svg|png)", str(f.get("path", ""))):
                warn(f"results.json: figure path should look like figures/<name>.svg: {f!r:.80}")
    info["tables"] = len(tables)
    info["figures"] = len(figures)
    return info


def check_replay(d) -> dict:
    info = {"available": None, "cases": 0}
    if not isinstance(d, dict):
        warn("replay.json is not an object")
        return info
    if not isinstance(d.get("available"), bool):
        warn("replay.json: 'available' should be true or false")
    info["available"] = d.get("available") is True
    cases = d.get("cases") if isinstance(d.get("cases"), list) else []
    if info["available"]:
        seen = set()
        for i, c in enumerate(cases):
            if not isinstance(c, dict) or not c.get("case_id"):
                warn(f"replay.json: case {i} has no case_id")
                continue
            cid = c["case_id"]
            if cid in seen:
                warn(f"replay.json: duplicate case_id {cid}")
            seen.add(cid)
            if c.get("stratum") not in STRATA:
                warn(f"replay.json: case {cid} has unknown stratum {c.get('stratum')!r}")
            if not re.fullmatch(r"[0-9a-f]{40}", str(c.get("commit", ""))):
                warn(f"replay.json: case {cid} commit is not 40 hex characters")
            ref = c.get("reference") or {}
            label = ref.get("label") if isinstance(ref, dict) else None
            if label is not None and label not in LABELS:
                warn(f"replay.json: case {cid} reference label {label!r} is not one of the five labels")
            preds = c.get("predictions") or {}
            for m in ("B1", "B2"):
                p = preds.get(m) if isinstance(preds, dict) else None
                if isinstance(p, dict) and p.get("label") not in (None, *LABELS):
                    warn(f"replay.json: case {cid} {m} label {p.get('label')!r} is not one of the five labels")
    info["cases"] = len(cases)
    return info


# ----------------------------------------------------------------------------- paper page


class SectionIndex(HTMLParser):
    """Collect <section id=...> elements and the text of their first heading."""

    HEADINGS = {"h1", "h2", "h3", "h4", "h5", "h6"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.stack: list[dict | None] = []
        self.entries: list[dict] = []
        self.capture: dict | None = None
        self.capture_tag: str | None = None
        self.scripts = 0

    def handle_starttag(self, tag, attrs):
        if tag == "script":
            self.scripts += 1
        if tag == "section":
            sid = dict(attrs).get("id")
            entry = None
            if sid:
                depth = sum(1 for e in self.stack if e is not None)
                entry = {"id": sid, "depth": depth, "title": "", "done": False}
                self.entries.append(entry)
            self.stack.append(entry)
        elif tag in self.HEADINGS and self.stack and self.capture is None:
            top = self.stack[-1]
            if top is not None and not top["done"]:
                self.capture, self.capture_tag = top, tag

    def handle_endtag(self, tag):
        if tag == "section" and self.stack:
            self.stack.pop()
        elif self.capture is not None and tag == self.capture_tag:
            self.capture["done"] = True
            self.capture = None

    def handle_data(self, data):
        if self.capture is not None:
            self.capture["title"] += data


def toc_html(entries: list[dict]) -> str:
    items = [e for e in entries if " ".join(e["title"].split())]
    if len(items) < 2:
        return ""
    base = min(e["depth"] for e in items)
    parts = ['  <nav class="toc" aria-labelledby="toc-title">', '    <h2 id="toc-title">Contents</h2>']
    open_lists = 0
    prev = 0
    for e in items:
        d = e["depth"] - base
        title = esc(" ".join(e["title"].split()))
        li = f'<li><a href="#{esc(e["id"])}">{title}</a>'
        if open_lists == 0:
            parts.append("<ol>")
            open_lists, d = 1, 0
        elif d > prev:
            d = prev + 1
            parts.append("<ol>")
            open_lists += 1
        else:
            parts.append("</li>")
            while prev > d:
                parts.append("</ol></li>")
                prev -= 1
                open_lists -= 1
        parts.append(li)
        prev = d
    parts.append("</li>")
    while open_lists > 1:
        parts.append("</ol></li>")
        open_lists -= 1
    parts.append("</ol>")
    parts.append("  </nav>")
    return "\n".join(parts)


def extract_body(fragment: str) -> str:
    m = re.search(r"<body[^>]*>(.*)</body>", fragment, flags=re.S | re.I)
    return m.group(1) if m else fragment


def paragraphs(text: str) -> str:
    blocks = [b.strip() for b in re.split(r"\n\s*\n", str(text or "")) if b.strip()]
    return "\n".join(f"<p>{esc(' '.join(b.split()))}</p>" for b in blocks)


def human_size(n: int) -> str:
    if n >= 1 << 20:
        return f"{n / (1 << 20):.1f} MB"
    return f"{max(1, round(n / 1024))} KB"


def render_template(template: str, values: dict[str, str]) -> str:
    # Single pass, so inserted content is never re-scanned for placeholders.
    return re.sub(r"\{\{(\w+)\}\}", lambda m: values.get(m.group(1), ""), template)


def build_paper(paper_dir: Path, out: Path, built_utc: str) -> dict:
    out_paper = out / "paper"
    out_paper.mkdir(parents=True, exist_ok=True)
    html_src = paper_dir / "paper.html"
    meta_src = paper_dir / "meta.json"
    pdf_src = paper_dir / PDF_NAME
    info = {"html": False, "pdf": False, "figures": 0}

    # Figures referenced as figures/<name>.svg (shared with the results page).
    fig_count = 0
    for fig_dir in (paper_dir / "figures",):
        if fig_dir.is_dir():
            (out_paper / "figures").mkdir(exist_ok=True)
            for f in sorted(fig_dir.iterdir()):
                if f.is_file() and f.suffix.lower() in (".svg", ".png"):
                    shutil.copyfile(f, out_paper / "figures" / f.name)
                    fig_count += 1
    info["figures"] = fig_count

    pdf_hash = None
    pdf_size = 0
    if pdf_src.is_file():
        shutil.copyfile(pdf_src, out_paper / PDF_NAME)
        pdf_hash = sha256(out_paper / PDF_NAME)
        pdf_size = (out_paper / PDF_NAME).stat().st_size
        info["pdf"] = True

    meta = read_json(meta_src) if meta_src.is_file() else None
    if meta is not None and not isinstance(meta, dict):
        warn("paper meta.json is not an object; treating the manuscript as not built")
        meta = None
    if meta is not None and pdf_hash and meta.get("pdf_sha256") and meta["pdf_sha256"].lower() != pdf_hash:
        warn("cipher-paper.pdf SHA-256 differs from meta.json pdf_sha256 (PDF and HTML may come from different builds)")

    template = (TEMPLATES / "paper.html").read_text(encoding="utf-8")
    actions = []
    if pdf_hash:
        actions.append(f'        <li><a class="bar-btn primary" href="{PDF_NAME}" type="application/pdf">Download PDF <span class="bar-sub">({human_size(pdf_size)})</span></a></li>')
    else:
        actions.append('        <li><span class="bar-btn" aria-disabled="true">PDF not yet compiled</span></li>')
    actions.append(f'        <li><a class="bar-btn" href="{GITHUB_URL}">Code</a></li>')

    built_day = built_utc[:10]
    build_note_bits = [f"Page generated by site/build.py on {esc(built_day)}."]
    if pdf_hash:
        build_note_bits.append(f'PDF SHA-256: <span class="mono">{esc(pdf_hash)}</span>')

    if html_src.is_file() and meta is not None:
        info["html"] = True
        fragment = extract_body(html_src.read_text(encoding="utf-8-sig"))
        index = SectionIndex()
        index.feed(fragment)
        index.close()
        if index.scripts:
            warn("paper.html contains <script> elements; they will run on the paper page")
        toc = toc_html(index.entries)

        bibtex = str(meta.get("citation_bibtex") or "").strip()
        if bibtex:
            actions.append('        <li><button type="button" class="bar-btn" id="cite-btn" aria-describedby="cite-help">Cite</button></li>')
        title = str(meta.get("title") or "").strip()
        if not title:
            warn("meta.json has no title")
        authors = meta.get("authors") if isinstance(meta.get("authors"), list) else []
        author_items = []
        for a in authors:
            if not isinstance(a, dict):
                continue
            bits = [f'<span class="author-name">{esc(a.get("name"))}</span>']
            if a.get("affiliation"):
                bits.append(f'<span class="author-aff">{esc(a.get("affiliation"))}</span>')
            if a.get("email"):
                bits.append(f'<span class="author-email">{esc(a.get("email"))}</span>')
            author_items.append("<li>" + "".join(bits) + "</li>")
        meta_line = " &middot; ".join(esc(x) for x in (
            f"Version {meta['version']}" if meta.get("version") else None,
            meta.get("date"),
        ) if x)

        has_own_abstract = re.search(r"""id\s*=\s*["']abstract["']""", fragment) is not None
        abstract = ""
        if meta.get("abstract") and not has_own_abstract:
            abstract = (
                '<section class="abstract" aria-labelledby="abstract-title">'
                '<h2 id="abstract-title">Abstract</h2>' + paragraphs(meta["abstract"]) + "</section>"
            )
        cite = ""
        if bibtex:
            cite = (
                '<section class="cite-box" id="cite" aria-labelledby="cite-title">'
                '<h2 id="cite-title">Cite this paper</h2>'
                '<p id="cite-help" class="visually-hidden">Copies the BibTeX entry shown at the end of the page.</p>'
                f'<pre id="bibtex" tabindex="0" aria-label="BibTeX entry">{esc(bibtex)}</pre>'
                '<p id="cite-status" class="visually-hidden" role="status" aria-live="polite"></p>'
                "</section>"
            )
        content = "\n".join([
            '    <article class="paper" aria-labelledby="paper-title">',
            '      <header class="paper-front">',
            f'        <h1 class="paper-title" id="paper-title">{esc(title) or "Untitled manuscript"}</h1>',
            f'        <ul class="authors" aria-label="Authors">{"".join(author_items)}</ul>' if author_items else "",
            f'        <p class="doc-meta">{meta_line}</p>' if meta_line else "",
            "      </header>",
            f"      {abstract}",
            '      <div class="paper-body">',
            fragment,
            "      </div>",
            f"      {cite}",
            "    </article>",
        ])
        description = " ".join(str(meta.get("abstract") or title).split())[:180]
        page_title = f"{title} \u00b7 Paper" if title else "CIPHER paper"
        layout_class = " has-toc" if toc else ""
        build_note_bits.insert(0, "Web version of the manuscript, generated from paper/build/paper.html.")
    else:
        missing = []
        for p, label in ((html_src, "paper/build/paper.html"), (meta_src, "paper/build/meta.json"), (pdf_src, f"paper/build/{PDF_NAME}")):
            state = "present" if p.is_file() else "not found"
            missing.append(f"<li><code>{esc(label)}</code>: {state}</li>")
        pdf_line = (
            f'<p>The compiled PDF exists: <a href="{PDF_NAME}">download {PDF_NAME}</a> ({human_size(pdf_size)}).</p>'
            if pdf_hash else ""
        )
        content = "\n".join([
            '    <div class="not-built">',
            '      <p class="status-pill">Manuscript not yet built</p>',
            "      <h1>CIPHER paper</h1>",
            '      <p class="lede">The web version of the manuscript has not been built yet. No draft or placeholder text is published in its place.</p>',
            f"      {pdf_line}",
            "      <p>This page is generated by <code>site/build.py</code> from the manuscript build outputs. At the last site build:</p>",
            "      <ul>" + "".join(missing) + "</ul>",
            f'      <p><a href="../index.html">Back to the project home</a> &middot; <a href="{GITHUB_URL}">Code on GitHub</a></p>',
            "    </div>",
        ])
        toc = ""
        layout_class = ""
        description = "The CIPHER manuscript has not been built yet."
        page_title = "Paper (not yet built) \u00b7 CIPHER"

    page = render_template(template, {
        "page_title": esc(page_title),
        "description": esc(description),
        "actions": "\n".join(actions),
        "toc": toc,
        "layout_class": layout_class,
        "content": content,
        "build_note": " ".join(build_note_bits),
    })
    (out_paper / "index.html").write_text(page, encoding="utf-8")
    return info


# ----------------------------------------------------------------------------- main


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Build the CIPHER static site into site/dist/.")
    ap.add_argument("--exports-dir", type=Path, default=DEFAULT_EXPORTS,
                    help="directory with status.json, results.json, replay.json (default: analysis/exports)")
    ap.add_argument("--paper-build-dir", type=Path, default=DEFAULT_PAPER,
                    help="directory with paper.html, meta.json, cipher-paper.pdf, figures/ (default: paper/build)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory (default: site/dist)")
    args = ap.parse_args(argv)

    exports: Path = args.exports_dir
    paper_dir: Path = args.paper_build_dir
    out: Path = args.out
    built_utc = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")

    print(f"Building CIPHER site -> {out}")

    # Parse every export before touching the output, so a malformed file leaves the previous build intact.
    sources: list[tuple[str, Path, object]] = []
    if exports.is_dir():
        for src in sorted(exports.glob("*.json")):
            key = src.stem
            if not re.fullmatch(r"[A-Za-z0-9_-]+", key) or key == "build":
                warn(f"skipping export with unsupported name: {src.name}")
                continue
            sources.append((key, src, read_json(src)))

    clean_out(out)
    shutil.copytree(SRC, out)
    out_data = out / "data"
    out_data.mkdir(exist_ok=True)

    # 1. Generated data.
    present: dict[str, bool] = {}
    loaded: dict[str, object] = {}
    if exports.is_dir():
        for key, src, data in sources:
            if key == "status" and isinstance(data, dict) and "git_commit" not in data:
                # the analysis export is commit-independent; the site records the commit it was built from
                head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=Path(__file__).resolve().parent,
                                      capture_output=True, text=True).stdout.strip()
                data = {**data, "git_commit": head} if head else data
            write_data(out_data, key, data, raw_source=None if key == "status" else src)
            present[key] = True
            loaded[key] = data
            print(f"  data: copied {display_path(src)}")
        fig_dir = exports / "figures"
        if fig_dir.is_dir():
            (out / "paper" / "figures").mkdir(parents=True, exist_ok=True)
            for f in sorted(fig_dir.iterdir()):
                if f.is_file() and f.suffix.lower() in (".svg", ".png"):
                    shutil.copyfile(f, out / "paper" / "figures" / f.name)
    for key in REQUIRED_EXPORTS:
        if key in loaded:
            continue
        reason = f"analysis/exports/{key}.json was not present when this site was built."
        stub = {"available": False, "stub": True, "reason": reason}
        if key == "results":
            stub.update({"tables": [], "figures": [], "limitations": []})
        elif key == "replay":
            stub.update({"cases": []})
        write_data(out_data, key, stub)
        present[key] = False
        print(f"  data: {key}.json missing -> wrote stub (available: false)")

    if present.get("status"):
        check_status(loaded["status"])
    results_info = check_results(loaded["results"]) if present.get("results") else {"available": False, "tables": 0, "figures": 0}
    replay_info = check_replay(loaded["replay"]) if present.get("replay") else {"available": False, "cases": 0}

    # 2. Paper page, PDF and figures.
    paper_info = build_paper(paper_dir, out, built_utc)
    print(f"  paper: web version {'built' if paper_info['html'] else 'NOT built'}; "
          f"PDF {'copied' if paper_info['pdf'] else 'not present'}; {paper_info['figures']} figure file(s)")

    if results_info.get("available"):
        for f in (loaded["results"].get("figures") or []):
            p = str(f.get("path", "")) if isinstance(f, dict) else ""
            if p and not (out / "paper" / p).is_file():
                warn(f"results.json references {p}, which is not in paper/build/figures or exports/figures")

    # 3. Build information (no research numbers; only what was present).
    build = {
        "site_built_utc": built_utc,
        "inputs": {"exports_dir": display_path(exports), "paper_build_dir": display_path(paper_dir)},
        "outputs": {
            "status": {"present": present.get("status", False)},
            "results": {"present": present.get("results", False), **results_info},
            "replay": {"present": present.get("replay", False), **replay_info},
            "paper": paper_info,
        },
    }
    write_data(out_data, "build", build)
    (out / ".nojekyll").write_text("", encoding="utf-8")

    print(f"Done: {display_path(out) if out.resolve().is_relative_to(REPO) else out}"
          f" ({len(warnings)} warning{'s' if len(warnings) != 1 else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
